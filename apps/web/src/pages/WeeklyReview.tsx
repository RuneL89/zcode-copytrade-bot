import { useEffect, useState } from 'react';
import { api } from '../api';

/**
 * Read-only weekly review viewer. The server generates the report from the
 * database on demand; this page only renders the returned markdown.
 */
export function WeeklyReviewPage({ onBack }: { onBack: () => void }) {
  const [week, setWeek] = useState('');
  const [data, setData] = useState<{ week: string; markdown: string } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const load = (label = week) => {
    setLoading(true);
    setError(null);
    api
      .weeklyReview(label.trim() || undefined)
      .then((result) => setData({ week: result.week, markdown: result.markdown }))
      .catch((e: Error) => setError(e.message))
      .finally(() => setLoading(false));
  };

  useEffect(() => {
    load('');
    // The initial load is the last completed week; explicit weeks use the form.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  return (
    <div className="pb-24">
      <div className="flex items-center justify-between pt-5 pb-3 gap-3">
        <div>
          <h1 className="text-[17px] font-bold">Weekly review</h1>
          <p className="label !text-[10px] !text-faint mt-0.5">
            promised vs actual · exits · hiring rules · fired traders
          </p>
        </div>
        <div className="flex items-center gap-3">
          <button
            onClick={() => load()}
            disabled={loading}
            className="label !text-[10.5px] underline cursor-pointer disabled:opacity-40"
          >
            {loading ? 'loading…' : 'refresh'}
          </button>
          <button onClick={onBack} className="label !text-[10.5px] underline cursor-pointer">
            ← dashboard
          </button>
        </div>
      </div>

      <form
        className="card p-3 mb-3.5 flex flex-wrap items-end gap-2"
        onSubmit={(event) => {
          event.preventDefault();
          load();
        }}
      >
        <label className="label !text-[10.5px] flex-1 min-w-[180px]">
          ISO week (blank = last completed)
          <input
            value={week}
            onChange={(event) => setWeek(event.target.value)}
            placeholder="2026-W46"
            className="mt-1 w-full rounded-[10px] border border-glassborder bg-inset px-3 py-2 text-[12px] text-ink placeholder:text-faint"
          />
        </label>
        <button
          type="submit"
          className="chip border border-accentborder bg-accentdim text-accent px-4 py-2 text-[12px] font-semibold cursor-pointer"
        >
          Generate
        </button>
        <span className="label !text-[10px] !text-faint">
          Read-only: the generator reads the DB and writes nothing.
        </span>
      </form>

      {error && (
        <p className="text-[12px] text-neg mb-3" role="alert">
          {error}
        </p>
      )}

      {data && (
        <section className="card p-4" aria-label={`weekly review ${data.week}`}>
          <div className="flex items-center justify-between mb-2">
            <p className="label">Report · {data.week}</p>
            <p className="label !text-[10px] !text-faint">markdown generated by the server</p>
          </div>
          <pre className="whitespace-pre-wrap break-words font-mono text-[11.5px] leading-relaxed text-ink overflow-x-auto max-h-[72svh] overflow-y-auto">
            {data.markdown}
          </pre>
        </section>
      )}
      {!data && !error && (
        <p className="text-[12px] text-muted">{loading ? 'generating…' : 'no report yet'}</p>
      )}
    </div>
  );
}
